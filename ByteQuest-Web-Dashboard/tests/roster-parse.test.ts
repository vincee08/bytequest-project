import assert from "node:assert/strict";
import { test } from "node:test";
import * as XLSX from "xlsx";
import {
  ROSTER_COLUMNS,
  ROSTER_MAX_BYTES,
  ROSTER_MAX_ROWS,
  buildRosterTemplate,
  normalizeRosterHeader,
  parseRosterFile,
} from "../src/lib/roster/parse";

type Cell = string | number | null;

function workbook(rows: Cell[][], bookType: XLSX.BookType = "xlsx", sheetName = "Roster") {
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(rows), sheetName);
  return new Uint8Array(XLSX.write(book, { type: "buffer", bookType }) as Buffer);
}

function parse(name: string, bytes: Uint8Array) {
  return parseRosterFile({ name, size: bytes.byteLength, bytes });
}

const HEADERS = ["student_id", "last_name", "first_name", "email", "course_section"];

test("the downloadable template uses the exact roster headers and an ignored example row", () => {
  const template = buildRosterTemplate();
  const book = XLSX.read(template, { type: "buffer" });
  assert.equal(book.SheetNames[0], "Roster");
  const rows = XLSX.utils.sheet_to_json<Cell[]>(book.Sheets.Roster, { header: 1, defval: "" });
  assert.deepEqual(rows[0], [...ROSTER_COLUMNS]);
  assert.match(String(rows[1][0]), /^EXAMPLE/);
  assert.match(String(rows[1][4]), /example/i);
  const parsed = parse("bytequest-roster-template.xlsx", new Uint8Array(template));
  assert.equal(parsed.ok, false);
  if (!parsed.ok) {
    assert.equal(parsed.code, "NO_DATA_ROWS");
    assert.match(parsed.message, /example row/i);
  }
});

test("header variants map by case, spaces, underscores and punctuation", () => {
  for (const [header, column] of [
    ["Student ID", "student_id"], ["STUDENT_ID", "student_id"], ["Student No.", "student_id"], ["Last Name", "last_name"],
    ["Surname", "last_name"], ["first name", "first_name"], ["Given Name", "first_name"], ["E-mail", "email"],
    ["Email Address", "email"], ["Course / Section", "course_section"], ["Section", "course_section"],
  ] as const) {
    assert.equal(normalizeRosterHeader(header), column, header);
  }
  assert.equal(normalizeRosterHeader("Middle Name"), null);
  const parsed = parse("roster.xlsx", workbook([
    ["Student ID", "LAST NAME", "First_Name", "E-mail", "Course / Section"],
    ["2024-001", "Dela Cruz", "Juan", "juan@school.edu.ph", "CSS NC II - A"],
  ]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.deepEqual(parsed.rows, [{ row_number: 2, student_id: "2024-001", last_name: "Dela Cruz", first_name: "Juan", email: "juan@school.edu.ph", course_section: "CSS NC II - A" }]);
    assert.equal(parsed.headerRow, 1);
  }
});

test("blank rows are skipped and row numbers still match the spreadsheet", () => {
  const parsed = parse("roster.xlsx", workbook([
    HEADERS,
    ["2024-001", "Cruz", "Juan", "juan@school.edu.ph", "A"],
    [],
    [null, "  ", null, "", null],
    ["2024-002", "Santos", "Maria", "maria@school.edu.ph", "A"],
  ]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.deepEqual(parsed.rows.map((row) => row.row_number), [2, 5]);
    assert.equal(parsed.blankRowsSkipped, 2);
  }
});

test("a legacy .xls workbook generated by SheetJS is parsed the same way", () => {
  const bytes = workbook([
    ["Student ID", "Last Name", "First Name", "Email", "Section"],
    ["2024-010", "Reyes", "Ana", "ANA.REYES@School.edu.ph", "B"],
  ], "biff8");
  assert.equal(Buffer.from(bytes.slice(0, 4)).toString("hex"), "d0cf11e0");
  const parsed = parse("legacy-roster.xls", bytes);
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.equal(parsed.format, "xls");
    assert.deepEqual(parsed.rows, [{ row_number: 2, student_id: "2024-010", last_name: "Reyes", first_name: "Ana", email: "ana.reyes@school.edu.ph", course_section: "B" }]);
  }
});

test("extra columns are ignored and reported", () => {
  const parsed = parse("roster.xlsx", workbook([
    ["Student ID", "Last Name", "First Name", "Middle Name", "Email", "Remarks", "Section"],
    ["2024-001", "Cruz", "Juan", "Santos", "juan@school.edu.ph", "transferee", "A"],
  ]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.deepEqual(parsed.ignoredColumns, ["Middle Name", "Remarks"]);
    assert.deepEqual(Object.keys(parsed.rows[0]).sort(), ["course_section", "email", "first_name", "last_name", "row_number", "student_id"]);
  }
});

test("emails are trimmed and lower-cased; names collapse stray whitespace", () => {
  const parsed = parse("roster.xlsx", workbook([
    HEADERS,
    [" 2024-001 ", "  Dela   Cruz ", "Juan Carlos", "  Juan.Cruz@School.EDU.PH  ", null],
  ]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.deepEqual(parsed.rows[0], { row_number: 2, student_id: "2024-001", last_name: "Dela Cruz", first_name: "Juan Carlos", email: "juan.cruz@school.edu.ph", course_section: "" });
  }
});

test("numeric student IDs keep every digit", () => {
  const parsed = parse("roster.xlsx", workbook([HEADERS, [2024000123, "Cruz", "Juan", "juan@school.edu.ph", "A"]]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) assert.equal(parsed.rows[0].student_id, "2024000123");
});

test("a title row above the headers and an example row are tolerated", () => {
  const parsed = parse("roster.xlsx", workbook([
    ["BSIT 2A — CSS NC II roster"],
    [],
    HEADERS,
    ["EXAMPLE-0001", "Dela Cruz", "Juan", "juan.delacruz@example.com", "Example row - ignored on import"],
    ["2024-001", "Cruz", "Juan", "juan@school.edu.ph", "A"],
  ]));
  assert.equal(parsed.ok, true);
  if (parsed.ok) {
    assert.equal(parsed.headerRow, 3);
    assert.equal(parsed.exampleRowsSkipped, 1);
    assert.deepEqual(parsed.rows.map((row) => row.row_number), [5]);
  }
});

test("missing required columns are named", () => {
  const parsed = parse("roster.xlsx", workbook([["Student ID", "Last Name", "First Name", "Section"], ["1", "Cruz", "Juan", "A"]]));
  assert.equal(parsed.ok, false);
  if (!parsed.ok) {
    assert.equal(parsed.code, "HEADERS_MISSING");
    assert.match(parsed.message, /email/);
  }
});

test("files above 2 MB are rejected before parsing", () => {
  const bytes = new Uint8Array(ROSTER_MAX_BYTES + 1);
  bytes.set([0x50, 0x4b, 0x03, 0x04]);
  const parsed = parse("roster.xlsx", bytes);
  assert.equal(parsed.ok, false);
  if (!parsed.ok) {
    assert.equal(parsed.code, "FILE_TOO_LARGE");
    assert.match(parsed.message, /2 MB/);
  }
});

test("more than 1000 learner rows are rejected instead of partially imported", () => {
  const rows: Cell[][] = [HEADERS];
  for (let index = 0; index <= ROSTER_MAX_ROWS; index += 1) rows.push([`S-${index}`, "Learner", `N${index}`, `learner${index}@school.edu.ph`, "A"]);
  const parsed = parse("roster.xlsx", workbook(rows));
  assert.equal(parsed.ok, false);
  if (!parsed.ok) {
    assert.equal(parsed.code, "TOO_MANY_ROWS");
    assert.match(parsed.message, /1,?000/);
  }
});

test("wrong file types are rejected with a clear message", () => {
  const csv = new TextEncoder().encode("student_id,last_name,first_name,email\n1,Cruz,Juan,juan@school.edu.ph\n");
  for (const [name, bytes] of [
    ["roster.csv", csv],
    ["roster.pdf", new Uint8Array([0x25, 0x50, 0x44, 0x46])],
    ["roster.xlsx", csv],
    ["roster.xls", new TextEncoder().encode("<html><table><tr><td>student_id</td></tr></table></html>")],
  ] as const) {
    const parsed = parse(name, bytes);
    assert.equal(parsed.ok, false, name);
    if (!parsed.ok) {
      assert.equal(parsed.code, "FILE_TYPE", name);
      assert.match(parsed.message, /\.xlsx/);
    }
  }
});

test("empty and unreadable workbooks fail safely", () => {
  const empty = parse("roster.xlsx", new Uint8Array());
  assert.equal(empty.ok, false);
  if (!empty.ok) assert.equal(empty.code, "FILE_EMPTY");
  const corrupt = new Uint8Array(512);
  corrupt.set([0x50, 0x4b, 0x03, 0x04, 1, 2, 3, 4]);
  const unreadable = parse("roster.xlsx", corrupt);
  assert.equal(unreadable.ok, false);
  if (!unreadable.ok) {
    assert.equal(unreadable.code, "FILE_UNREADABLE");
    assert.doesNotMatch(unreadable.message, /Error|stack|at /);
  }
});
