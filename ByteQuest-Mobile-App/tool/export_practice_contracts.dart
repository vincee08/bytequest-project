import 'dart:convert';
import 'dart:io';

import 'package:bytequest/data/mission_simulation_definitions.dart';

// Run with dart from the mobile directory after changing practice definitions.
// This publishes only deterministic practice constraints, never official rubrics.
void main(List<String> args) {
  if (args.length != 1) {
    throw ArgumentError(
        'Provide an explicit output path for a new migration or temporary drift comparison.');
  }
  final rows =
      MissionSimulationDefinitions.all.where((d) => d.cocId != 'coc4').map((d) {
    final json = jsonEncode(d.toJson()).replaceAll("'", "''");
    return "('${d.id}', 'css-sag-20261011-v2', '$json'::jsonb)";
  }).join(',\n');
  File(args.single).writeAsStringSync(
      '-- Generated by tool/export_practice_contracts.dart.\n'
      'begin;\ninsert into public.practice_mission_contracts(mission_id,version,definition) values\n'
      '$rows\non conflict(mission_id) do update set version=excluded.version,definition=excluded.definition;\ncommit;\n');
}
