// Run with dart from the mobile directory after changing practice definitions.
// This publishes only deterministic practice constraints, never official rubrics.
//
//   dart run tool/export_practice_contracts.dart <out.sql> [missionId]
//       Bulk COC1-COC3 contract upsert (legacy drift comparison).
//   dart run tool/export_practice_contracts.dart --assembly-migration <out.sql>
//       Writes the COC1 M2 assembly-bench contract migration.
//   dart run tool/export_practice_contracts.dart --check-assembly-migration <file>
//       Exits 1 when the committed migration drifts from the typed definition.
//   dart run tool/export_practice_contracts.dart --replay-fixtures <out.sql>
//       Writes the happy-path rows used by supabase/tests/simulation_*.sql.

const assemblyMigrationFileName =
    '20261119110200_coc1_m2_assembly_contract.sql';

/// SHA-256 of [assemblyContractMigrationSql]. Changing the COC1 M2 typed
/// definition changes this digest: publish a new contract migration (never
/// edit an applied one) and update the digest together.
const assemblyMigrationSha256 =
    '8829b7ed191188f9f0fce2100831949c708eac5c28b0ae89f20e2f4d018df2c3';

String _contractJson(MissionSimulationDefinition definition) =>
    jsonEncode(definition.toJson()).replaceAll("'", "''");

String bulkContractSql({String? missionId}) {
  if (missionId != null &&
      !MissionSimulationDefinitions.all
          .any((d) => d.id == missionId && d.cocId != 'coc4')) {
    throw ArgumentError.value(missionId, 'missionId');
  }
  final rows = MissionSimulationDefinitions.all
      .where(
          (d) => d.cocId != 'coc4' && (missionId == null || d.id == missionId))
      .map((d) =>
          "('${d.id}', '${MissionSimulationDefinitions.contractVersion(d.id)}', "
          "'${_contractJson(d)}'::jsonb)")
      .join(',\n');
  return '-- Generated by tool/export_practice_contracts.dart.\n'
      'begin;\ninsert into public.practice_mission_contracts(mission_id,version,definition) values\n'
      '$rows\non conflict(mission_id) do update set version=excluded.version,definition=excluded.definition;\ncommit;\n';
}

/// The complete, deterministic COC1 M2 assembly-bench contract migration.
String assemblyContractMigrationSql() {
  final definition = MissionSimulationDefinitions.byId('coc1_m2');
  const version = MissionSimulationDefinitions.coc1M2AssemblyContractVersion;
  return '''-- Generated by tool/export_practice_contracts.dart --assembly-migration.
-- Do not edit by hand; regenerate from the typed Flutter definition.
--
-- COC1 M2 practice contract $version: the realistic assembly bench
-- (prepare, motherboard preparation, case installation, power and data,
-- power-on test, review). Practice evidence, completions and runs are never
-- rewritten. Verified completions of css-sag-20261009-v1 and
-- css-sag-20261011-v2 keep counting (module completion and the COC1 practice
-- quiz gate) through public.practice_completion_accepted (20261119120000).
-- Each POST check names the step target it charges ("counts"); see
-- 20261119110400.
begin;

do \$guard\$
declare current_contract public.practice_mission_contracts;
begin
  select * into strict current_contract from public.practice_mission_contracts
    where mission_id = 'coc1_m2' for update;
  if current_contract.version not in ('css-sag-20261011-v2', '$version') then
    raise exception 'COC1_M2_V2_CONTRACT_REQUIRED' using errcode = '22023';
  end if;
end
\$guard\$;

insert into public.practice_mission_contracts(mission_id, version, definition) values
('coc1_m2', '$version', '${_contractJson(definition)}'::jsonb)
on conflict(mission_id) do update
  set version = excluded.version, definition = excluded.definition
  where public.practice_mission_contracts.version = 'css-sag-20261011-v2';

notify pgrst, 'reload schema';
commit;
''';
}

String assemblyContractMigrationDigest() =>
    sha256.convert(utf8.encode(assemblyContractMigrationSql())).toString();

/// Action value keys the server replay reads (see private.simulation_replay).
const replayValueKeys = {
  'item_id',
  'destination_id',
  'orientation',
  'source_id',
  'values',
  'order',
  'confirmed',
  'tool_id',
  'selection_group',
  'selected_ids',
  'observation',
  'interpretation',
  'runtime_action_type',
  'test_status',
};

/// The action kinds the server replay evaluates; anything else (navigation,
/// phase completion, review) is recorded but never replayed.
const replayActionKinds = {
  'object_inspected',
  'placement_attempted',
  'placement_removed',
  'connection_created',
  'configuration_applied',
  'sequence_reordered',
  'tool_attempted',
  'selection_confirmed',
  'scenario_decision',
  'diagnostic_action',
  'equipment_operation',
  'test_started',
  'test_completed',
  'observation_recorded',
  'result_interpreted',
};

/// The replay-relevant form of an evidence action, as the server sees it.
Map<String, Object?> replayRow(MissionEvidenceAction action) => {
      'phase_id': action.phaseId,
      'kind': action.value['runtime_action_type'] ?? action.actionType,
      'target': action.target,
      'value': {
        for (final entry in action.value.entries)
          if (replayValueKeys.contains(entry.key) &&
              entry.key != 'runtime_action_type')
            entry.key: entry.value,
      },
    };

String _sqlText(String? value) =>
    value == null ? 'null' : "'${value.replaceAll("'", "''")}'";

/// Happy-path evidence for every typed definition, in the column order of the
/// replay suites' `replay_fixture` table. Values keep only the keys the
/// server replay reads; client snapshots and measurements are never trusted.
String replayFixtureSql() {
  final rows = <String>[];
  for (final definition in MissionSimulationDefinitions.all) {
    final driver = EquipmentPracticeDriver(definition);
    for (final phase in definition.phases) {
      driver.complete(phase);
    }
    var ordinal = 0;
    for (final action in driver.actions) {
      ordinal++;
      final value = {
        for (final entry in action.value.entries)
          if (replayValueKeys.contains(entry.key)) entry.key: entry.value,
      };
      rows.add("('${definition.id}', $ordinal, '${action.phaseId}', "
          "'${action.actionType}', ${_sqlText(action.target)}, "
          "${_sqlText(jsonEncode(value))}::jsonb)");
    }
  }
  return '-- Generated by tool/export_practice_contracts.dart --replay-fixtures.\n'
      'insert into replay_fixture(mission_id, ordinal, phase_id, action_type, target, value) values\n'
      '${rows.join(',\n')};\n';
}

void main(List<String> args) {
  if (args.length == 2 && args.first == '--assembly-migration') {
    File(args[1]).writeAsStringSync(assemblyContractMigrationSql());
    stdout.writeln('sha256 ${assemblyContractMigrationDigest()}');
    return;
  }
  if (args.length == 2 && args.first == '--check-assembly-migration') {
    // Git may check the file out with CRLF line endings on Windows.
    final committed =
        File(args[1]).readAsStringSync().replaceAll('\r\n', '\n');
    final expected = assemblyContractMigrationSql();
    final digest = assemblyContractMigrationDigest();
    if (committed != expected || digest != assemblyMigrationSha256) {
      stderr.writeln('COC1 M2 assembly contract migration drifted '
          '(generated sha256 $digest, recorded $assemblyMigrationSha256).');
      exitCode = 1;
      return;
    }
    stdout.writeln('COC1 M2 assembly contract migration matches ($digest).');
    return;
  }
  if (args.length == 2 && args.first == '--replay-fixtures') {
    File(args[1]).writeAsStringSync(replayFixtureSql());
    return;
  }
  if (args.isEmpty || args.length > 2 || args.first.startsWith('--')) {
    throw ArgumentError(
        'Provide an output path and optionally one mission ID for a new migration or drift comparison.');
  }
  File(args.first).writeAsStringSync(
      bulkContractSql(missionId: args.length == 2 ? args[1] : null));
}
